// src/store/selectors.js — СЕЛЕКТОРЫ, зависящие от нескольких слайсов.

// Идёт ли сейчас ГЛОБАЛЬНАЯ загрузка (спиннер на весь экран: LoadingOverlay).
// Учитываются авторизация и лекарства. Поставщики сюда НЕ входят: у второй формы
// свой локальный спиннер прямо над формой и таблицей (компонент LoadingBlock),
// иначе на экране были бы сразу два спиннера.
//
// Ошибки читаются отдельными селекторами, поэтому спиннер и ошибки друг другу не мешают:
// пока статус "loading" — ошибка уже сброшена (см. pending в слайсах), а как только
// пришёл ответ — спиннер исчезает и ошибка видна.
export const selectIsLoading = (state) =>
  state.auth.status === "loading" || state.medicines.status === "loading";
