// src/utils/delay.js — ИМИТАЦИЯ ЗАДЕРЖКИ СЕТИ.
// Настоящего сервера нет, сервисы отвечают мгновенно. Чтобы спиннер загрузки
// было видно (и чтобы thunk'и вели себя как настоящие запросы), ждём ms миллисекунд.

export const delay = (ms) => new Promise((resolve) => setTimeout(resolve, ms)); // Promise, который выполнится через ms мс
